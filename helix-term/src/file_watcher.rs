use std::{
    collections::HashSet,
    path::{Path, PathBuf},
    sync::mpsc::{self, Receiver, TryRecvError},
};

use notify::{Event, EventKind, RecommendedWatcher, RecursiveMode, Watcher};

/// Watches the workspace root and the directories currently expanded in the
/// file tree. Only non-recursive watches are installed, so large ignored trees
/// such as `target/` are not watched until the user expands them.
pub struct FileWatcher {
    rx: Receiver<notify::Result<Event>>,
    watcher: RecommendedWatcher,
    watched: HashSet<PathBuf>,
}

impl FileWatcher {
    pub fn new(root: &Path) -> notify::Result<Self> {
        let (tx, rx) = mpsc::channel();
        let watcher =
            notify::recommended_watcher(move |result: notify::Result<Event>| match result {
                Ok(event) => {
                    // Access events are generated by merely reading files, so they
                    // would cause a lot of unnecessary refreshes.
                    if !matches!(event.kind, EventKind::Access(_)) {
                        let _ = tx.send(Ok(event));
                        helix_event::request_redraw();
                    }
                }
                Err(err) => {
                    let _ = tx.send(Err(err));
                    helix_event::request_redraw();
                }
            })?;
        let mut watcher = Self {
            rx,
            watcher,
            watched: HashSet::new(),
        };
        watcher.watch(root)?;
        Ok(watcher)
    }

    fn watch(&mut self, path: &Path) -> notify::Result<()> {
        if !self.watched.insert(path.to_owned()) {
            return Ok(());
        }

        if let Err(err) = self.watcher.watch(path, RecursiveMode::NonRecursive) {
            self.watched.remove(path);
            return Err(err);
        }

        Ok(())
    }

    fn unwatch(&mut self, path: &Path) {
        if self.watched.remove(path) {
            let _ = self.watcher.unwatch(path);
        }
    }

    /// Synchronize the set of watched directories with the directories that are
    /// currently visible in the tree.
    pub fn sync(&mut self, root: &Path, expanded: &HashSet<PathBuf>) {
        let desired: HashSet<&Path> = std::iter::once(root)
            .chain(expanded.iter().map(PathBuf::as_path))
            .collect();

        let stale: Vec<PathBuf> = self
            .watched
            .iter()
            .filter(|path| !desired.contains(path.as_path()) || !path.is_dir())
            .cloned()
            .collect();
        for path in stale {
            self.unwatch(&path);
        }

        let missing: Vec<PathBuf> = desired
            .iter()
            .copied()
            .filter(|path| !self.watched.contains(*path))
            .map(Path::to_owned)
            .collect();
        for path in missing {
            // A path in `expanded` may refer to a directory that was removed
            // while the sidebar was hidden. Skip those instead of logging an
            // error on every sync.
            if !path.is_dir() {
                continue;
            }
            if let Err(err) = self.watch(&path) {
                log::warn!("failed to watch {}: {err}", path.display());
            }
        }
    }

    /// Drain pending events. Returns true if anything relevant changed.
    pub fn poll(&mut self) -> bool {
        let mut changed = false;

        loop {
            match self.rx.try_recv() {
                Ok(Ok(event)) => {
                    if !matches!(event.kind, EventKind::Access(_)) && !event.paths.is_empty() {
                        changed = true;
                    }
                }
                Ok(Err(err)) => log::warn!("file watcher error: {err}"),
                Err(TryRecvError::Empty | TryRecvError::Disconnected) => break,
            }
        }

        changed
    }
}
